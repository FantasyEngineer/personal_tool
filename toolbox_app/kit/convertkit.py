def ratio_converters(factors):
    """乘数类单位：先折算到该类的基准单位，再从基准单位摊回每个目标单位。"""
    return ([lambda v, f=f: v * f for f in factors],
            [lambda t, f=f: t / f for f in factors])


def temp_converters():
    """温度有偏移量，套不进乘数：℉ 和 K 都先折回 ℃（℃ 就是这类的基准）。"""
    return ([lambda v: v,
             lambda v: (v - 32) * 5.0 / 9.0,
             lambda v: v - 273.15],
            [lambda c: c,
             lambda c: c * 9.0 / 5.0 + 32,
             lambda c: c + 273.15])


def unit_format(v):
    """整数就不带小数点，否则保留 6 位有效数字。"""
    if abs(v) < 1e15 and v == int(v):
        return str(int(v))
    return "%.6g" % v


def base_convert(text, src_base, dst_base):
    """按 src_base 把 text 读成整数，再按 dst_base 输出；text 非法时抛 ValueError。"""
    cleaned = text.replace("0x", "").replace("0X", "").replace(" ", "")
    value = int(cleaned, src_base)
    if dst_base == 2:
        return bin(value).replace("0b", "")
    if dst_base == 8:
        return oct(value).replace("0o", "")
    if dst_base == 16:
        return hex(value).replace("0x", "").upper()
    return str(value)
